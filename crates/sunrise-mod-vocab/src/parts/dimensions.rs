impl dyn Registrar + '_ {
    /// Register dimension `name` (`pocket` or `mymod:pocket`) once at startup:
    /// every world then has that level, shaped and generated by
    /// `settings`, as if a data pack below all the others gave it. A data pack
    /// can replace its level stem or dimension type. A bare name uses this mod's
    /// namespace; an explicit valid `namespace:path` keeps its namespace. An
    /// empty or malformed name, a name that is no folder of the world (`../x`,
    /// `a//b`, capitals), a vanilla level, an id registered twice, a build height
    /// the dimension type codec refuses and an unknown generator refuse the mods
    /// at startup, naming the mod.
    pub fn register_dimension(&mut self, name: &str, settings: crate::DimensionSettings) {
        self.add_dimension(name, settings);
    }
    /// Register world clock `name` (`dungeon` or `mymod:dungeon`) once at startup: a
    /// `minecraft:world_clock` registry entry (`WorldClock`), as if a data pack below all the
    /// others gave it, that a dimension type names as its default clock
    /// ([`DimensionSettings::clock`](crate::DimensionSettings::clock)). It counts its own time,
    /// saved with the world, which `level.clock(host)` sets for the levels that follow it (a
    /// paused clock is a fixed time). An unowned namespace, an empty name, a name that is no
    /// folder of the world, a vanilla clock and an id registered twice refuse the mods at
    /// startup, naming the mod.
    pub fn register_world_clock(&mut self, name: &str) {
        self.add_world_clock(name);
    }
    /// Register chunk generator `name` (`void` or `mymod:void`) once at
    /// startup: a level whose stem names that id then has the terrain of
    /// `generator`, whose [`build_terrain`](crate::ChunkGenerator::build_terrain)
    /// runs on the worldgen worker threads. The level gets the vanilla stages
    /// its [`vanilla_stages`](crate::ChunkGenerator::vanilla_stages) asks for,
    /// read here, once. A bare name uses this mod's namespace; an explicit valid
    /// `namespace:path` keeps its namespace. A malformed name, a name that is no
    /// folder of the world, a built-in chunk generator and an id registered twice
    /// refuse the mods at startup, naming the mod.
    pub fn register_chunk_generator<T: crate::ChunkGenerator>(&mut self, name: &str, generator: T) {
        self.add_chunk_generator(name, Arc::new(generator));
    }
    /// Register biome source `name` (`chaos` or `mymod:chaos`) once at
    /// startup: a level whose stem's `biome_source` is `{"type": "mymod:chaos"}`,
    /// or whose [`DimensionSettings`](crate::DimensionSettings) name it in
    /// `mod_biome_source`, then takes its biomes from `source`, whose
    /// [`noise_biome`](crate::BiomeSource::noise_biome) runs on the worldgen
    /// worker threads. It serves the game's noise generator, its structures and
    /// decoration included, and a mod's chunk generator. Its
    /// [`possible_biomes`](crate::BiomeSource::possible_biomes) are read here,
    /// once. A bare name uses this mod's namespace; an explicit valid
    /// `namespace:path` keeps its namespace. A malformed name, a name that is no
    /// folder of the world, a built-in biome source, an id registered twice and
    /// an empty biome list refuse the mods at startup, naming the mod.
    pub fn register_biome_source<T: crate::BiomeSource>(&mut self, name: &str, source: T) {
        self.add_biome_source(name, Arc::new(source));
    }
}

/// Registrar operations for dimensions.
pub trait DimensionsRegistrar {
    /// Register dimension `name` with `settings`; mods reach it through
    /// `register_dimension`.
    fn add_dimension(&mut self, name: &str, settings: crate::DimensionSettings);
    /// Register world clock `name`; mods reach it through `register_world_clock`.
    fn add_world_clock(&mut self, name: &str);
    /// Register chunk generator `name` with `generator`; mods reach it through
    /// `register_chunk_generator`.
    fn add_chunk_generator(&mut self, name: &str, generator: Arc<dyn crate::ChunkGenerator>);
    /// Register biome source `name` with `source`; mods reach it through
    /// `register_biome_source`.
    fn add_biome_source(&mut self, name: &str, source: Arc<dyn crate::BiomeSource>);
}
