#!/usr/bin/env python3
"""Regenerate tools/file_size_baseline.txt for a sync PR, or for a rollup that carries one.

Only a sync uses the file (docs/layers.md#file-size): its sync-baseline header names the upstream commit the
sync merges, and each entry caps one file at the exact size the sync leaves it. Nobody edits entries by hand:
on a conflict in the file, or after the sync's code changed, run

    python3 tools/sync/write_file_size_baseline.py --base origin/main --marker <full upstream SHA>

An entry is written for each Rust file that is over the limit and grew past its size on the merge base with
`--base`, at its current size; every other file is left to the plain rule, so the file stays small and nothing
in it goes stale. Generated files and third_party/ are skipped, as the check skips them. `--marker` is
required when something grew (the sync declares its upstream commit); without growth the existing header is
kept. `--check` prints the result and leaves the file alone.
"""

import argparse
from pathlib import Path
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from tools import check_file_size  # noqa: E402

BASELINE = "tools/file_size_baseline.txt"
COMMENTS = (
    "# Sync-only restoration ratchet, generated by tools/sync/write_file_size_baseline.py.",
    "# The full SHA must be a new merge parent outside the base; see tools/sync/README.md.",
)


def grown(entries):
    """{path: current code lines} for each checked file over the limit that grew past its merge-base size."""
    return {path: now for path, before, now, is_generated in sorted(entries)
            if not path.startswith(check_file_size.EXEMPT_PREFIXES) and not is_generated
            and now > check_file_size.LIMIT and now > before}


def render(marker, sizes):
    lines = list(COMMENTS)
    if marker is not None:
        lines.append(f"# sync-baseline: {marker}")
    lines.extend(f"{path} {size}" for path, size in sizes.items())
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--base", required=True, help="the git ref the branch starts from (CI: the pull request's base)")
    parser.add_argument("--marker", help="the full SHA of the upstream commit this sync merges")
    parser.add_argument("--check", action="store_true", help="print the file instead of writing it")
    args = parser.parse_args(argv)

    root = check_file_size.ROOT
    merge_base, entries = check_file_size.scan(args.base)
    sizes = grown(entries)
    file = root / BASELINE
    current, _ = check_file_size.parse_baseline(file.read_text() if file.exists() else "")
    old = subprocess.run(["git", "show", f"{merge_base}:{BASELINE}"], cwd=root, capture_output=True, encoding="utf-8")
    previous, _ = check_file_size.parse_baseline(old.stdout if old.returncode == 0 else "")
    marker = args.marker or current
    if sizes and (marker is None or marker == previous):
        print("Files grew past their merge-base size: a sync declares the upstream commit it merges, "
              "pass --marker <full upstream SHA> (the SHA must be new compared with the base).", file=sys.stderr)
        return 2
    try:
        check_file_size.parse_baseline(render(marker, sizes))
    except ValueError as error:
        print(f"Refusing to write: {error}", file=sys.stderr)
        return 2
    text = render(marker, sizes)
    if args.check:
        print(text, end="")
        return 0
    file.write_text(text)
    print(f"Wrote {BASELINE}: {len(sizes)} entries" + (f", sync-baseline {marker}." if marker else "."))
    return 0


if __name__ == "__main__":
    sys.exit(main())
