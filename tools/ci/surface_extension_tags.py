"""Generate the package fence and book catalogs from the vocabulary's extension-tag inputs.

Add one JSON file per family in crates/sunrise-mod-vocab/extension-tags/, then run
python3 tools/ci/surface_extension_tags.py. --check is the verify-static drift guard.
A family file is an array of declarations or the path to an engine-owned declaration.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DIRECTORY = ROOT / "crates/sunrise-mod-vocab/extension-tags"
OUTPUT = ROOT / "crates/sunrise-mod-package/src/extension_tags.rs"


def catalog(declarations: list[tuple[Path, list[dict[str, str]]]]) -> str:
    out = ['// Generated by python3 tools/ci/surface_extension_tags.py; do not edit.\n',
           '//! Extension points declared beside their engine readers.\n',
           '/// A tag to which a package may add data in the reserved engine namespace.\n',
           '#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n',
           'pub struct ExtensionTag {\n',
           '    /// Tag directory registry.\n    pub registry: &\'static str,\n',
           '    /// Namespaced tag identifier.\n    pub id: &\'static str,\n',
           '    /// The reader\'s contract.\n    pub doc: &\'static str,\n}\n']
    seen = set()
    families = {}
    for path, rows in declarations:
        family = path.stem.upper()
        if not family.isidentifier() or family in families:
            raise ValueError(f'{path}: invalid or duplicate family name')
        families[family] = len(rows)
        out.append(f'pub const {family}: &[ExtensionTag] = &[\n')
        for row in rows:
            if set(row) != {'registry', 'id', 'doc'} or not all(isinstance(v, str) and v for v in row.values()):
                raise ValueError(f'{path}: expected registry, id and doc strings')
            key = (row['registry'], row['id'])
            if key in seen or not row['id'].startswith('sunrise:') or row['id'].startswith('sunrise:class/'):
                raise ValueError(f'{path}: invalid or duplicate extension tag {key}')
            seen.add(key)
            out.append('    ExtensionTag {\n')
            for field in ('registry', 'id', 'doc'):
                out.append(f'        {field}: {json.dumps(row[field], ensure_ascii=False)},\n')
            out.append('    },\n')
        out.append('];\n')
    out.append('pub const ALL: &[ExtensionTag] = &[\n')
    for family, count in families.items():
        for i in range(count):
            out.append(f'    {family}[{i}],\n')
    out.append('];\n')
    return ''.join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    page = ['# Extension tags\n\n', '<!-- Generated by python3 tools/ci/surface_extension_tags.py; do not edit. -->\n\n',
            'Packages may add to exactly these tags in the reserved `sunrise` namespace.\n',
            'Normal tag merging applies, including `replace: true`. Other reserved files remain refused.\n',
            'Generated `sunrise:class/*` tags cannot be written; attach a part with `block_part_tag` instead.\n\n',
            '| Registry | Tag | Contract |\n| --- | --- | --- |\n']
    declarations = []
    for path in sorted(DIRECTORY.iterdir()):
        if path.suffix == '.json' and path.is_file():
            rows = json.loads(path.read_text())
            if isinstance(rows, str):
                rows = json.loads((ROOT / rows).read_text())
            if not isinstance(rows, list):
                raise ValueError(f'{path}: expected a JSON array of extension tags')
            declarations.append((path, rows))
    rust = catalog(declarations)
    for _, rows in declarations:
        for row in rows:
            page.append(f"| `{row['registry']}` | `{row['id']}` | {row['doc']} |\n")
    outputs = {OUTPUT: rust, ROOT / 'docs/modding/src/how-to/extension-tags.md': ''.join(page)}
    for path, expected in outputs.items():
        if args.check:
            if path.read_text() != expected:
                raise SystemExit(f'{path.name} is stale; run python3 tools/ci/surface_extension_tags.py')
        else:
            path.write_text(expected)


if __name__ == '__main__':
    main()
